def eyeball(cx, cy, rx, ry, lx=0, ly=0):
    """眼睛：INK 圆点 + 白高光（与第 1 段统一画法）。"""
    return E(cx, cy, rx, ry, INK) + C(cx + lx, cy + ly, max(3.0, rx * 0.34), WHITE)


def point_fist(x, y, s, cuff=TEAL, cuff_d=TEAL_D):
    """指点的小手：握拳+独食指水平指向左侧，指尖落在 (x-128s, y)。"""
    g = (R(-128, -22, 132, 44, 22, SKIN)                           # 食指
         + L(-96, -18, -96, 18, SKIN_D, 5) + L(-56, -18, -56, 18, SKIN_D, 5)
         + E(-118, -8, 12, 8, SKIN_L, 0.8)
         + R(0, -46, 96, 92, 30, SKIN)                             # 拳身
         + E(28, -48, 24, 15, SKIN)                                # 拇指鼓包
         + R(6, 46, 84, 44, 20, cuff) + R(6, 46, 84, 12, 6, cuff_d))
    return f'<g transform="translate({x},{y}) scale({s})">{g}</g>'


