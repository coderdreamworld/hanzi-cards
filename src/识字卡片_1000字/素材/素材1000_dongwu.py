def eyes(cx, cy, dx, rx=10, ry=12, dark=INK):
    return wrap(
        E(cx - dx, cy, rx, ry, dark), C(cx - dx - 3, cy - 4, 3.2, WHITE),
        E(cx + dx, cy, rx, ry, dark), C(cx + dx - 3, cy - 4, 3.2, WHITE))


def eyes_side(cx, cy, rx=8, ry=10, dark=INK):
    return E(cx, cy, rx, ry, dark) + C(cx - 3, cy - 3, 2.8, WHITE)


def blush(cx, cy, dx, r=12):
    return C(cx - dx, cy, r, PINK, 0.75) + C(cx + dx, cy, r, PINK, 0.75)


def smile(cx, cy, w=16, drop=13, dark=INK, sw=5):
    return P(f"M {cx - w} {cy} Q {cx} {cy + drop} {cx + w} {cy}", stroke=dark, w=sw)


def body(cx, cy, rx, ry, main, dark):
    return E(cx + rx * 0.06, cy + ry * 0.13, rx, ry, dark) + E(cx, cy, rx, ry, main)


def head(cx, cy, r, main, dark):
    return C(cx + r * 0.07, cy + r * 0.13, r, dark) + C(cx, cy, r, main)


def leg(x, y, w=26, h=64, main=None, dark=None, hoof=16):
    main = main or SAND
    dark = dark or SAND_D
    return R(x, y, w, h, w * 0.46, main) + R(x, y + h - hoof, w, hoof, hoof * 0.45, dark)


def toes(cx, cy, dx, dark, sw=4):
    return (L(cx - dx, cy, cx - dx + 8, cy, dark, sw) +
            L(cx + dx - 8, cy, cx + dx, cy, dark, sw) +
            L(cx - 1, cy, cx + 1, cy, dark, sw))


