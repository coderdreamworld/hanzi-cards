def plate(cx=380, cy=414, rx=180, ry=34):
    """白瓷果盘：碟影 + 白碟 + 碟心。"""
    return (E(cx, cy + 8, rx, ry, PLATE_SH) + E(cx, cy, rx, ry, "#fdfdfa")
            + E(cx, cy, rx * 0.68, ry * 0.64, PLATE_IN))


def steam_wisp(x, y, h, lean=16, w=10):
    """一道 S 形热气。"""
    return P(f"M {x} {y} Q {x - lean} {y - h * 0.32} {x} {y - h * 0.58} "
             f"Q {x + lean} {y - h * 0.82} {x - 2} {y - h}", stroke=STEAM_C, w=w, opacity=0.9)


def bowl_body(cx, rim_y, r, depth, main, dark, foot=True):
    """侧视碗身：rim_y=碗口沿 y，depth=碗深，可带圈足。"""
    g = P(f"M {cx - r} {rim_y} Q {cx - r + 2} {rim_y + depth * 0.62} {cx - r * 0.42} {rim_y + depth * 0.88} "
          f"Q {cx} {rim_y + depth} {cx + r * 0.42} {rim_y + depth * 0.88} "
          f"Q {cx + r - 2} {rim_y + depth * 0.62} {cx + r} {rim_y} Z", main)
    if foot:
        g += R(cx - r * 0.26, rim_y + depth - 4, r * 0.52, 16, 8, dark)
    return g


def leaf_pt(cx, cy, ln, wd, rot, main, vein=None):
    """尖头叶片：基点在 (cx,cy)，叶尖朝上，rot 旋转。"""
    g = P(f"M 0 0 Q {wd * 0.55} {-ln * 0.34} 0 {-ln} Q {-wd * 0.55} {-ln * 0.34} 0 0 Z", main)
    if vein:
        g += L(0, -8, 0, -ln + 10, vein, 3.5)
    return f'<g transform="translate({cx},{cy}) rotate({rot})">{g}</g>'


def crystal(x, y, s, rot):
    """一粒盐晶：小白方块 + 暖灰投影。"""
    shade = R(-s * 0.5 + 1.6, -s * 0.5 + 1.6, s, s, 2, GRAIN_SH)
    grain = R(-s * 0.5, -s * 0.5, s, s, 2, "#fdfdfa")
    return f'<g transform="translate({x},{y}) rotate({rot})">{shade}{grain}</g>'


def sp_leaf(fill, s=1.0, vein=None):
    """菠菜叶：宽身长水滴，基点在原点、叶尖朝上。"""
    g = P(f"M 0 0 C {-50 * s} {-48 * s} {-58 * s} {-130 * s} {-14 * s} {-190 * s} "
          f"C {-6 * s} {-202 * s} {6 * s} {-202 * s} {14 * s} {-190 * s} "
          f"C {58 * s} {-130 * s} {50 * s} {-48 * s} 0 0 Z", fill)
    if vein:
        g += L(0, -12, 0, -182 * s, vein, 4)
    return g


