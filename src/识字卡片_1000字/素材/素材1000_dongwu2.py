def web(cx, cy, r, color="#bdb6a8"):
    """蛛网：8 辐 + 三层八边环。"""
    g = ""
    for i in range(8):
        a = i * math.pi / 4
        g += L(cx, cy, cx + r * math.cos(a), cy + r * math.sin(a), color, 4)
    for rr in (r * 0.36, r * 0.66, r * 0.95):
        pts = []
        for i in range(8):
            a = i * math.pi / 4 + math.pi / 8
            pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
        g += P("M " + " L ".join(f"{x:.1f} {y:.1f}" for x, y in pts) + " Z",
               stroke=color, w=4)
    return g


def centipede_legs(pts, color, w=6, ln=20):
    """沿给定点画多对足（前后两撇）。"""
    g = ""
    for (x, y) in pts:
        g += L(x - 3, y, x - 14, y + ln, color, w)
        g += L(x + 4, y, x + 12, y + ln, color, w)
    return g


