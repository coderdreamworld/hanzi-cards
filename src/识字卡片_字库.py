def flatten():
    """返回 [(group_id, group_name, 卡片标识, 说明), ...]。"""
    out = []
    for g in GROUPS:
        for item in g["chars"]:
            key = item["char"] if isinstance(item, dict) else item
            out.append((g["id"], g["name"], key, g["kind"]))
    return out


def all_chars():
    seen = []
    for _, _, key, _ in flatten():
        chars = list(key) if isinstance(key, tuple) else [key]
        seen.extend(chars)
    return seen


